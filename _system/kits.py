# ---------------------------------------------------------------- rendering helpers
def anchor(s):  # the id GitHub gives a Markdown heading
    return re.sub(r'[^\w\- ]', '', s.strip().lower()).replace(' ', '-')


def pl(n, word, many=None):
    return f'{n} {word if n == 1 else many or word + "s"}'


def fence(code, lang=''):
    n = max([3] + [len(x) + 1 for x in re.findall(r'`{3,}', code)])
    return f"{'`' * n}{lang}\n{code}\n{'`' * n}"


def md_block(s, bk):
    """Several lines of plain text: each line made Markdown-safe, list markers and fenced code kept."""
    out, code = [], None
    for ln in str(s).strip('\n').split('\n'):
        if code is not None:
            out.append(ln)
            if ln.strip().startswith(code) and not ln.strip().strip(code[0]): code = None
            continue
        m = FENCE.fullmatch(ln.strip())
        if m and ln.lstrip().startswith(('```', '~~~')): code = m[1]; out.append(ln.strip()); continue
        m = re.match(r'(\s*)([-*+] |\d+[.)] )?(.*)', ln)
        out.append(m[1] + (m[2] or '') + bk.md(m[3]) if m[3].strip() else '')
    if code is not None: out.append(code)
    return '\n'.join(out)


def csv_text(rows):
    buf = io.StringIO(newline='')
    w = csv.writer(buf, lineterminator='\n')
    w.writerows(rows)
    return buf.getvalue()


