def link_text(s, bk):  # Markdown link text: brackets escaped, so a placeholder like "[Company name]" shows as written
    return bk.md(s).replace('[', '\\[').replace(']', '\\]')


# ---------------------------------------------------------------- who said it
def speakers(s):
    return [x for x in (s.get('speaker') if isinstance(s.get('speaker'), list) else [s.get('speaker')]) if isinstance(x, str) and x.strip()]


def person(x):
    return isinstance(x, str) and x[:1].isupper() and not GENERIC.search(x)


def people(S):
    """Person names that speak in the sessions, and the Googlers among them (they speak outside lightning and poster slots)."""
    names = {x for s in S.values() for x in speakers(s) if person(x)}
    google = {x for s in S.values() if s.get('kind', 'talk') not in ('lightning', 'poster') for x in speakers(s) if person(x)}
    return names, google


def inferred(name, s):
    t = f"{s.get('role') or ''} {s.get('note') or ''}"
    return 'speaker inferred' in t.lower() or re.search(re.escape(name) + r"[^.;]*\binferred\b", t, re.I) is not None


def proven(c, S):
    """The claim's speaker when it is proven: a person's name in `who` that sessions.yaml does not mark as inferred."""
    if c.get('label') not in EVENT or c.get('s') not in S: return None
    w = c.get('who')
    return w if person(w) and not inferred(w, S[c['s']]) else None


def who_short(c, S, google, sources):
    """Google, a community speaker, or 'a speaker' when nothing recorded says which (a D<day>-S00 point, or a lightning slot with a Google host)."""
    if c['label'] == 'analysis': return 'the author'
    if c['label'] in ('docs', 'press'): return ', '.join(dict.fromkeys(sources[k]['publisher'] for k in c.get('src', []) if k in sources))
    s, w = S[c['s']], c.get('who')
    if w == 'audience': return 'an audience member'
    if isinstance(w, str) and w != 'unknown' and not person(w):  # who: Google, a community speaker
        return 'Google' if 'google' in w.lower() else 'a community speaker' if 'community' in w.lower() else 'a speaker'
    if s.get('kind', 'talk') in ('lightning', 'poster'):
        if person(w): return 'Google' if w in google else 'a community speaker'
        return 'a speaker' if any(x in google or 'google' in x.lower() for x in speakers(s)) else 'a community speaker'
    if not speakers(s): return 'Google' if person(w) and w in google else 'a speaker'  # D<day>-S00: no speaker list to go by
    return 'Google'


def documented(c):
    return c.get('ver') in ('confirmed', 'consistent') or c.get('label') == 'docs'


def grade(cs):
    if any(documented(c) for c in cs): return 'documented'
    if any(c.get('label') in EVENT for c in cs): return 'event-only'
    return 'press' if any(c.get('label') == 'press' for c in cs) else 'analysis'


def grade_point(cs):
    """An angle point: 'mixed' when it rests on documented claims and on event claims the documentation does not back."""
    g = grade(cs)
    return 'mixed' if g == 'documented' and any(c.get('label') in EVENT and not documented(c) and c.get('who') != 'audience' for c in cs) else g


# ---------------------------------------------------------------- links: what rests on a claim (knowledge graph, phase 0)
# Every kit item is a node of the agent pack's graph.json and links.json: <prefix>:<key>, e.g. req:DEV-SRV-01, fact:F-012,
# term:crawl-budget (a glossary term's key is the term made a slug by build_kb.node_slug). Lists of items follow KIND_ORDER, then key.
KIND_ORDER = ('requirement', 'fact', 'myth', 'quote', 'angle', 'term')
PREFIX = {'requirement': 'req', 'fact': 'fact', 'myth': 'myth', 'quote': 'quote', 'angle': 'angle', 'term': 'term'}
KIT_FILE = {k: 'dev-requirements.json' if k == 'requirement' else 'content-library.json' for k in KIND_ORDER}


def quote_text(c, bk):
    return bk.nt(c.get('quote') or '').strip('"').strip('“”')


def item_claims(part, x):
    """The claim ids a kit item rests on, each once, in the order the kit lists them (an angle: every point's claims)."""
    if part == 'quotes': return [x['claim']]
    if part == 'angles': return list(dict.fromkeys(c for p in x['points'] for c in p['claims']))
    return list(dict.fromkeys(x['claims']))


def term_aliases(term, bk):
    """The spellings a glossary term is found by: the term itself; the part before a parenthesis and the part inside it (unless
    that is a list with commas): 'Crawl rate limit (hostload)'; and each part of 'A and B' or 'A, B and C': 'BERT, RankBrain and
    MUM'. Original spellings, first seen first, one per normalised key (build_kb.norm_key), each at least two characters long."""
    t = bk.nt(term)
    out = [t]
    m = re.fullmatch(r'(.+?)\s*\(([^()]+)\)', t)
    base = m[1] if m else t
    if m: out += [base] + ([m[2].strip()] if ',' not in m[2] else [])
    if re.search(r'\sand\s', base): out += [p.strip() for p in re.split(r',\s*|\s+and\s+', base)]
    keep, seen = [], set()
    for a in out:
        k = bk.norm_key(a)
        if len(k) >= 2 and k not in seen: seen.add(k); keep.append(a)
    return keep


def kit_items(kb, bk):
    """Every kit item as {node id: {kind, key, name, claims, topics, file[, aliases]}}, in KIND_ORDER then key. claims: the public
    claim ids it rests on; topics: the topic ids of those claims, most frequent first, ties in topics.yaml order. Computed once per
    build and kept in kb['kit_items']; build_kb.py uses it for used_by, topic pages, links.json and graph.json."""
    if 'kit_items' in kb: return kb['kit_items']
    kit, CL = kb['kits'], {c['id']: c for c in kb['claims'] if c.get('private') is not True}
    rank = {t: i for i, t in enumerate(kb['topics'])}
    ct = kit['content']
    raw = [('requirement', r['id'], r['title'], item_claims('requirements', r)) for a in kit['areas'] for r in a['requirements']]
    raw += [('fact', x['id'], x['statement'], item_claims('facts', x)) for x in ct['facts']]
    raw += [('myth', x['id'], x['myth'], item_claims('myths', x)) for x in ct['myths']]
    raw += [('quote', x['id'], quote_text(CL[x['claim']], bk), item_claims('quotes', x)) for x in ct['quotes']]
    raw += [('angle', x['id'], x['title'], item_claims('angles', x)) for x in ct['angles']]
    raw += [('term', bk.node_slug(x['term']), x['term'], item_claims('glossary', x)) for x in ct['glossary']]
    out = {}
    for kind, key, name, cids in sorted(raw, key=lambda r: (KIND_ORDER.index(r[0]), r[1])):
        n = Counter(t for x in cids for t in CL[x]['topics'])
        rec = {'kind': kind, 'key': key, 'name': bk.nt(name), 'claims': cids, 'topics': sorted(n, key=lambda t: (-n[t], rank[t])), 'file': KIT_FILE[kind]}
        if kind == 'term': rec['aliases'] = term_aliases(name, bk)
        out[f'{PREFIX[kind]}:{key}'] = rec
    kb['kit_items'] = out
    return out


def item_texts(kb, bk):
    """Each kit item's own words, one line, by node id: what build_kb.py matches the things against besides the item's claims. A
    requirement: title and why; a fact: the statement; a myth: the myth and its fact; a quote: the quotation; an angle: title, hook and
    points; a glossary term: the term and its definition. Parts are joined with ' · ' so no alias can run across two of them."""
    kit, CL = kb['kits'], {c['id']: c for c in kb['claims'] if c.get('private') is not True}
    ct, j = kit['content'], lambda *p: ' · '.join(bk.nt(x) for x in p)
    out = {f"req:{r['id']}": j(r['title'], r['why']) for a in kit['areas'] for r in a['requirements']}
    out.update({f"fact:{x['id']}": j(x['statement']) for x in ct['facts']})
    out.update({f"myth:{x['id']}": j(x['myth'], x['fact']) for x in ct['myths']})
    out.update({f"quote:{x['id']}": quote_text(CL[x['claim']], bk) for x in ct['quotes']})
    out.update({f"angle:{x['id']}": j(x['title'], x['hook'], *[p['text'] for p in x['points']]) for x in ct['angles']})
    out.update({f"term:{bk.node_slug(x['term'])}": j(x['term'], x['definition']) for x in ct['glossary']})
    return out


# ---------------------------------------------------------------- snippets
def parse_snippet(text, where, E, W):
    """A title line, a few sentences, and one or more fenced code blocks (prose between blocks becomes that block's note)."""
    title, prose, blocks, cur = None, [], [], None
    for ln in text.replace('\r\n', '\n').split('\n'):
        if cur is not None:
            if re.fullmatch(re.escape(cur['fence'][0]) + '{%d,}[ \t]*' % len(cur['fence']), ln.strip()): blocks.append(cur); cur = None
            else: cur['lines'].append(ln)
            continue
        m = FENCE.fullmatch(ln.strip()) if ln.lstrip().startswith(('```', '~~~')) else None
        if m: cur, prose = {'fence': m[1], 'lang': m[2], 'lines': [], 'note': ' '.join(prose)}, []; continue
        if not ln.strip(): continue
        if title is None: title = ln.strip().lstrip('#').strip(); continue
        prose.append(ln.strip())
    if cur is not None: E.append(f'{where}: the code block opened with {cur["fence"]} is never closed')
    if not title: E.append(f'{where}: the first line must be a short title'); title = ''
    if not blocks and cur is None: E.append(f'{where}: no fenced code block (```html ... ```)')
    text0 = blocks[0]['note'] if blocks else ' '.join(prose)
    if blocks: blocks[0]['note'] = ''
    if prose and blocks: W.append(f'{where}: text after the last code block is left out; put it before the code')
    if not text0: W.append(f'{where}: add one to three sentences between the title and the code')
    out = []
    for i, b in enumerate(blocks, 1):
        code = '\n'.join(b['lines']).strip('\n')
        lang = b['lang'].lower()
        tag = f'{where} code block {i}'
        if not code.strip(): E.append(f'{tag}: empty'); continue
        if not lang: W.append(f'{tag}: no language after the fence (```html, ```json, ```xml, ```http ...)')
        try:
            if lang in ('json', 'jsonld', 'json-ld'): json.loads(code)
            elif lang == 'xml' or lang.endswith('sitemap'): ET.fromstring(code.encode('utf-8'))
            if lang in ('html', 'htm', 'xhtml'):
                for j in LDJSON.findall(code): json.loads(j)
        except json.JSONDecodeError as x: E.append(f'{tag}: the JSON is not valid ({x})')
        except ET.ParseError as x: E.append(f'{tag}: the XML is not well-formed ({x})')
        out.append({'lang': lang, 'code': code, 'note': b['note']})
    return {'title': title, 'text': text0, 'code': out}


# ---------------------------------------------------------------- validation (nothing is written here)
def validate(root, kb, E, W, bk):
    """Check 25-kits/ against the claims, sources and sessions in kb; store the parsed kits in kb['kits']."""
    K = root / KITS
    claims = kb.get('claims') or []
    by_id = {c['id']: c for c in claims if isinstance(c, dict) and isinstance(c.get('id'), str)}
    public = {i for i, c in by_id.items() if c.get('private') is not True}
    sources, S = kb.get('sources') or {}, kb.get('sessions') or {}
    names, google = people(S)
    names |= {c['who'] for c in by_id.values() if person(c.get('who'))}
    n0 = len(E)
    dev, content, snippets = bk.read_yaml(K / 'dev-requirements.yaml', E), bk.read_yaml(K / 'content.yaml', E), {}
    for p in sorted((K / 'snippets').glob('*')) if (K / 'snippets').is_dir() else []:
        where = f'{KITS}/snippets/{p.name}'
        if p.suffix != '.md' or not p.is_file(): E.append(f'{where}: only <key>.md files belong in {KITS}/snippets/'); continue
        if not bk.KEBAB.fullmatch(p.stem): E.append(f'{where}: the file name must be a lowercase kebab-case key, e.g. canonical-link.md'); continue
        try: txt = p.read_text(encoding='utf-8')
        except UnicodeDecodeError: E.append(f'{where}: not UTF-8 text; save it as UTF-8'); continue
        snippets[p.stem] = dict(parse_snippet(txt, where, E, W), key=p.stem, raw=txt)
    if len(E) > n0: return

    def rec(x, where, keys, optional=()):
        if not isinstance(x, dict): E.append(f'{where}: must be a mapping'); return False
        for k in x:
            if k not in keys: E.append(f'{where}: unknown key "{k}"{bk.hint(k, keys)}')
        for k in keys:
            if k not in x and k not in optional: E.append(f'{where}: missing key "{k}"')
        return True

    def text(x, k, where, multi=False):
        v = x.get(k)
        if k not in x: return ''
        if not isinstance(v, str) or not v.strip(): E.append(f'{where}: {k} must be a non-empty string'); return ''
        if not multi and '\n' in v.strip(): W.append(f'{where}: {k} spans several lines; outputs join it into one')
        return v

    def cited(v, where, key='claims'):
        if not isinstance(v, list) or any(not isinstance(x, str) for x in v): E.append(f'{where}: {key} must be a list of claim ids, e.g. [D1-C001]'); return []
        if not v: E.append(f'{where}: {key} is empty; cite at least one public claim')
        bk.dups(v, f'{where}: {key}', E)
        for x in v:
            if not CID_FULL.fullmatch(x): E.append(f'{where}: {key} must list claim ids like D1-C001, found {x!r}')
            elif x not in by_id: E.append(f'{where}: cites {x}, which does not exist')
            elif x not in public: E.append(f'{where}: cites {x}, which is private')
        return [by_id[x] for x in v if x in public]

    def free(where, obj, cs):
        """Claim ids written in the text exist and are public, no excluded photo, and a person is named only on proof."""
        blob = json.dumps(obj, ensure_ascii=False, default=str)
        for x in bk.cited_ids(blob, where, E):
            if x not in by_id: E.append(f'{where}: mentions {x}, which does not exist')
            elif x not in public: E.append(f'{where}: mentions {x}, which is private')
        for x in bk.excluded_in(obj): E.append(f'{where}: names {x}, which must never appear in a shared output')
        if cs and re.search(r'community speaker', blob, re.I) and not any(c.get('label') in EVENT and who_short(c, S, google, sources) == 'a community speaker' for c in cs):
            E.append(f'{where}: says "community speaker", but none of its claims is a slide or stage claim credited to a community speaker; credit the speaker its claims name')
        ok = {proven(c, S) for c in cs}
        for n in sorted(names):
            if re.search(r'(?<!\w)' + re.escape(n) + r'(?!\w)', blob) and n not in ok:
                E.append(f'{where}: names {n}, but none of its claims is proven to be {n}\'s (who: {n}, not marked inferred in sessions.yaml); '
                         'leave the name out and credit "Google" or "a community speaker"')

    def status(st, where, cs):
        if not isinstance(st, str) or st not in STATUS: E.append(f'{where}: status must be documented or event-only, found {st!r}'); return
        if st == 'documented' and grade(cs) != 'documented' and cs:
            E.append(f'{where}: status documented, but none of its claims is confirmed, consistent or a docs claim; use event-only or cite the documentation')
        if st == 'event-only' and cs and not any(c.get('label') in EVENT for c in cs):
            E.append(f'{where}: status event-only needs at least one slide or stage claim')

    # ---- dev-requirements.yaml
    areas, req_ids, area_ids, used, codes = [], Counter(), Counter(), Counter(), {}
    if not isinstance(dev, dict) or not isinstance(dev.get('areas'), list): E.append(f'{KITS}/dev-requirements.yaml: needs areas: [...]'); dev = {'areas': []}
    for k in dev:
        if k not in DEV_KEYS: E.append(f'{KITS}/dev-requirements.yaml: unknown top-level key "{k}"{bk.hint(k, DEV_KEYS)}')
    for a in dev['areas']:
        aid = a.get('id') if isinstance(a, dict) else None
        wa = f'dev area {aid}'
        if not rec(a, wa, AREA_KEYS): continue
        if not isinstance(aid, str) or not bk.KEBAB.fullmatch(aid): E.append(f'{wa}: id must be lowercase kebab-case, e.g. status-codes')
        area_ids[str(aid)] += 1
        for k in ('title', 'intro'): text(a, k, wa, multi=k == 'intro')
        free(wa, {k: v for k, v in a.items() if k != 'requirements'}, [])
        reqs = a.get('requirements')
        if not isinstance(reqs, list) or not reqs: E.append(f'{wa}: requirements must be a non-empty list'); reqs = []
        good = []
        for r in reqs:
            rid = r.get('id') if isinstance(r, dict) else None
            wr = f'requirement {rid}'
            if not rec(r, wr, REQ_KEYS, optional=('snippet', 'docs')): continue
            m = REQ_ID.fullmatch(rid) if isinstance(rid, str) else None
            if not m: E.append(f'{wr}: id must look like DEV-REN-01 (DEV-, an area code in capitals, -, two digits)')
            else: codes.setdefault(m[1], set()).add(str(aid))
            req_ids[str(rid)] += 1
            if not isinstance(r.get('level'), str) or r['level'] not in LEVELS: E.append(f'{wr}: level must be one of {", ".join(LEVELS)}, found {r.get("level")!r}')
            for k in ('title', 'why', 'how', 'test'): text(r, k, wr, multi=k in ('why', 'how', 'test'))
            cs = cited(r.get('claims'), wr)
            docs = r.get('docs') or []
            if not isinstance(docs, list) or any(not isinstance(x, str) for x in docs): E.append(f'{wr}: docs must be a list of source keys, e.g. [robots-spec]'); docs = []
            bk.dups(docs, f'{wr}: docs', E)
            for k in docs:
                if k not in sources: E.append(f'{wr}: unknown docs key {k} (add it to 20-claims/sources.yaml first)')
                elif (sources[k].get('kind') or 'google') != 'google': E.append(f'{wr}: docs key {k} is a press source; docs lists Google pages only')
            st = r.get('status')
            if not isinstance(st, str) or st not in STATUS: E.append(f'{wr}: status must be documented or event-only, found {st!r}')
            elif st == 'documented' and not docs: E.append(f'{wr}: status documented needs at least one Google page in docs')
