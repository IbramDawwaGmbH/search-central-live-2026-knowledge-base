_QUAL = r'(?:(?:more than|over|about|around|roughly|nearly|almost|up to|at least|at most|under|fewer than|less than|exactly)\s+)?'
_NUM = r'(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?'
_UNIT = (r'(?:\s?(?:%|percent\b|per cent\b)|x\b|\s?(?:px|KiB|KB|MB|GB)\b|\s(?:times|thousand|million|billion|trillion|milliseconds?|seconds?|'
         r'minutes?|hours?|days?|weeks?|months?|years?(?![\s-]+olds?\b)|pixels?|words?|characters?)\b)')
FIGURE = re.compile(rf'(?<![\w.,/:-]){_QUAL}(?P<n>{_NUM})(?:\s?(?:-|–|to)\s?{_NUM})?(?:(?P<u>{_UNIT})|(?=[^\w%]|$))', re.I)
HEDGE = re.compile(r'\b(uncertain|unclear|could not be confirmed|not clear|inaudible|unintelligible recording|recordings disagree|best reading)', re.I)
TOP_SAID = 3  # claims per list in "What did Google say about X?"
LABEL_WORD = {'slide': 'slide', 'stage': 'stage', 'docs': 'docs', 'press': 'press', 'analysis': 'analysis'}


def figures(text):
    """The figures a text states, as written, each once: a number with a unit (%, times, million, hours, px ...) or a number written
    with thousands separators (10,000), keeping a range (1-2 weeks, 45 to 90 minutes) and a qualifier (more than, about, up to ...).
    Bare numbers (years, dates, days, status codes, version numbers) are not figures."""
    return list(dict.fromkeys(m[0].strip() for m in FIGURE.finditer(' '.join(str(text or '').split())) if m['u'] or ',' in m['n']))


